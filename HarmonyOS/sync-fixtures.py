"""Keep the gallery's bundled resources identical to the platform-neutral wire fixtures."""

import argparse
import json
from pathlib import Path

repo = Path(__file__).resolve().parent.parent
source = repo / "Sources" / "AIElementsUIProtocol" / "Resources"
destination = repo / "HarmonyOS" / "gallery" / "src" / "main" / "resources" / "rawfile"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="check for missing, stale, or unexpected fixtures")
arguments = parser.parse_args()

names = {path.name for path in source.glob("*.json") if path.stem not in {"schema", "dashboard"}}
names.add("dashboard.jsonl")
if arguments.check:
    actual = {path.name for path in destination.iterdir() if path.is_file()}
    stale = sorted(
        name for name in names & actual if (source / name).read_bytes() != (destination / name).read_bytes()
    )
    if names != actual or stale:
        parser.exit(1, f"Missing: {sorted(names - actual)}. Unexpected: {sorted(actual - names)}. Stale: {stale}.\n")
else:
    destination.mkdir(parents=True, exist_ok=True)
    for name in sorted(names):
        (destination / name).write_bytes((source / name).read_bytes())

# The desktop ArkUI Previewer mocks resourceManager raw-file reads. Embed the same
# fixture data in the HAR so gallery and device previews use the same public API.
catalog = repo / "Sources/AIElementsCatalog/Resources/shadcn-catalog.json"
module = repo / "HarmonyOS/aielements/src/main/ets/shadcn/CatalogData.ets"
entries = json.loads(catalog.read_text())
data = [json.dumps(entry, separators=(",", ":"), ensure_ascii=False) for entry in entries]
rendered = "// Generated by HarmonyOS/sync-fixtures.py from shadcn-catalog.json.\n"
rendered += "export const shadcnExamples: string[] = [\n"
rendered += "".join("  " + json.dumps(entry, ensure_ascii=False) + ",\n" for entry in data)
rendered += "];\n"
if arguments.check:
    if not module.exists() or module.read_text() != rendered:
        parser.exit(1, f"Stale shadcn catalog. Run {Path(__file__).name}.\n")
else:
    module.write_text(rendered)
